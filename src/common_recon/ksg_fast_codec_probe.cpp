static const KSG_FAST_REPLAY_FRAME g_Frames[] = {
    { 0xfdf251f2u, 0xc8607053u, 56, g_Frame1Cipher, g_Frame1Plain, sizeof(g_Frame1Plain) },
    { 0xc8607053u, 0x4bb61e12u, 56, g_Frame2Cipher, g_Frame2Plain, sizeof(g_Frame2Plain) },
    { 0x4bb61e12u, 0x33162833u, 56, g_Frame3Cipher, g_Frame3Plain, sizeof(g_Frame3Plain) },
    { 0x7e130733u, 0x4c566332u, 6, g_TailCipher, g_TailPlain, sizeof(g_TailPlain) }
};

int main()
{
    KSG_ENCODE_DECODE_FUNCTION pfnEncode = NULL;
    KSG_ENCODE_DECODE_FUNCTION pfnDecode = NULL;
    unsigned char byBuffer[64];
    size_t index;

    if (!_SetEncodeDecodeFunction(KSG_ENCODE_DECODE_FAST, &pfnEncode, &pfnDecode))
        return 1;
    if (pfnEncode != KSG_DecodeEncodeFast || pfnDecode != KSG_DecodeEncodeFast)
        return 2;

    for (index = 0; index < sizeof(g_Frames) / sizeof(g_Frames[0]); ++index)
    {
        unsigned uKey = g_Frames[index].uBeforeKey;
        memset(byBuffer, 0, sizeof(byBuffer));
        memcpy(byBuffer, g_Frames[index].pbyCipherPrefix, g_Frames[index].uPrefixSize);
        if (!pfnDecode(g_Frames[index].uSize, byBuffer, &uKey))
            return 3;
        if (uKey != g_Frames[index].uAfterKey)
            return 4;
        if (memcmp(byBuffer, g_Frames[index].pbyPlainPrefix, g_Frames[index].uPrefixSize) != 0)
            return 5;
    }
    return 0;
}
